// ------------------------------------------------------------
// PART 1: WHAT IS JAVASCRIPT? (in the simplest way possible)
// ------------------------------------------------------------
//
// Websites are usually built from 3 layers:
//   HTML  -> the STRUCTURE (the skeleton - headings, buttons, text)
//   CSS   -> the STYLE (the clothes - colors, layout, fonts)
//   JS    -> the BEHAVIOR (the brain - makes things happen: clicks,
//            calculations, loading data, animations)
//
// JavaScript is the ONLY one of the three that can make a webpage
// actually DO things, react to the user, and think/calculate.


// ------------------------------------------------------------
// PART 2: WHERE DOES JAVASCRIPT RUN?
// ------------------------------------------------------------
//
// 1. In the BROWSER (Chrome, Edge, etc.) - this is where it
//    controls webpages (this is what topics 6-10 cover).
// 2. On your COMPUTER directly, using Node.js - this is what
//    we've been doing with "node filename.js" in the terminal.
//
// Same language, two different places it can run.


